      h2 4.3 Estrategias para manejar las emociones

    p.mt-4(data-aos="fade-right") Las condiciones actuales del trabajo exigen más recursos emocionales que en otras épocas. La conectividad permanente acortó los tiempos de respuesta, de modo que un mensaje recibido en la noche o durante un día de descanso genera la sensación de que la jornada nunca termina. A esa presión se suman las reuniones virtuales encadenadas, la sobrecarga de información y la dificultad para separar el espacio laboral del personal, sobre todo en las modalidades remotas o alternadas.

