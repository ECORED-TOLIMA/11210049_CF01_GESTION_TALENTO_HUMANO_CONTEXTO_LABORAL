    p.mt-4(data-aos="fade-right") Reconocer los propios sentimientos y los de los demás, motivarse a uno mismo y manejar de manera adecuada las emociones en la vida personal y relacional constituye el núcleo de esta competencia. El concepto, formulado inicialmente por Salovey y Mayer (como se citó en Goleman, 2012), alcanzó difusión amplia gracias a los trabajos de este último sobre su aplicación en las organizaciones.

