        p(data-aos="fade-left") La alteridad es uno de los conceptos más valiosos para pensar éticamente en las relaciones humanas. Levinas (1982/2000) sostiene que el encuentro con el otro no puede reducirse a la propia manera de ver el mundo, pues su presencia interpela y genera responsabilidad. Reconocer esa condición supone aceptar que nadie está llamado a pensar ni a actuar exactamente como uno mismo y que la diferencia, lejos de constituir una amenaza, enriquece la vida colectiva.

        .bg-1.r-0.p-4.mt-4.mb-0(data-aos="fade-left")
          p.mb-0 En el entorno laboral convergen personas con trayectorias, expectativas, temperamentos y saberes diversos, de modo que esta noción desactiva la pretensión de homogeneidad. Las organizaciones requieren acuerdos y propósitos comunes, aunque no uniformidad en la manera de ser de sus integrantes. Al respecto, Robbins y Judge (2017) señalan que la diversidad bien gestionada amplía la variedad de perspectivas y favorece el aprendizaje, la innovación y la resolución de problemas, mientras que su manejo inadecuado incrementa los conflictos y la rotación del personal. Para que esa pluralidad se convierta en fortaleza, necesita estar mediada por el respeto.

    p.mt-4(data-aos="fade-right") El respeto es la actitud que reconoce el valor del otro y lo trata con consideración. No equivale a la ausencia de diferencias ni a la cortesía superficial, pues implica escuchar, no ridiculizar, no instrumentalizar y no descalificar la dignidad ajena. En el trabajo se expresa en conductas concretas: cumplir los compromisos, emplear un lenguaje adecuado, valorar el tiempo ajeno, tramitar los desacuerdos sin agresión y reconocer el aporte de los demás.

